def model_fixture(tmp_path):
    data = b"GGUFautomatic local model"
    digest = hashlib.sha256(data).hexdigest()
    path = tmp_path / ("sha256-" + digest)
    path.write_bytes(data)
    show = {
        "modelfile": f"# generated by Ollama\nFROM {path}\n",
        "details": {"format": "gguf", "quantization_level": "Q4_K_M"},
        "license": "full model license\n" * 100,
        "template": "{{ .System }} {{ .Prompt }} {{ .Response }}",
        "system": "custom system prompt",
        "parameters": 'temperature 0.25\nnum_ctx 4096\nstop "end-one"\nstop "end-two"\n',
        "capabilities": ["completion"],
    }
    tags = {"models": [{"name": "automatic:latest", "digest": "c" * 64}]}

    def backend(request):
        return httpx.Response(200, json=tags if request.url.path == "/api/tags" else show)

    return data, path, show, tags, httpx.MockTransport(backend)


@pytest.mark.asyncio
async def test_automatic_offers_still_require_signed_peer_authentication(tmp_path, monkeypatch):
    from test_rpc import enrolled, signed, worker

    from fleet_manager.peer.ollama_catalog import OllamaCatalog

    _, _, _, _, transport = model_fixture(tmp_path)
    async with (
        httpx.AsyncClient(transport=transport, base_url="http://ollama") as backend,
        worker(tmp_path / "worker", monkeypatch) as (app, authority, client),
    ):
        assert app.state.model_sharing.catalog is not None
        app.state.model_sharing.catalog = OllamaCatalog(backend)
        path = "/peer/v1/models/inventory"
        assert (await client.post(path, json={})).status_code == 403
        for name in ("trusted-one", "trusted-two"):
            peer = await enrolled(authority, tmp_path / name, name)
            body, headers = signed(peer, path, {})
            response = await client.post(path, content=body, headers=headers)
            assert response.status_code == 200
            peer.verify_response(headers["x-idle-nonce"], 200, response.content, response.headers)
            offer = ArtifactManifest.model_validate(response.json()["models"][0])
            assert offer.model_id == "automatic:latest"
            assert offer.calculated_digest() == offer.manifest_digest
            assert str(tmp_path) not in response.text
            assert (await client.post(path, content=body, headers=headers)).status_code == 403


@pytest.mark.asyncio
async def test_default_auto_catalog_transfer_preserves_options_and_reshares(tmp_path):
    data, _, show, _, transport = model_fixture(tmp_path)
    created = []

    async def backend(request):
        if request.url.path == "/api/tags":
            return httpx.Response(
                200,
                json={
                    "models": [{"name": "automatic:latest", "digest": "backend-digest"}]
                    if created
                    else []
                },
            )
        if request.url.path == "/api/create":
            created.append(json.loads(request.content))
            return httpx.Response(200, json={"status": "success"})
        assert await request.aread() == data
        return httpx.Response(201)

    async def load(_manifest):
        return True

    source = ModelSharing(
        tmp_path / "source", "http://ollama", transport=transport, discover_installed=True
    )
    dest = ModelSharing(
        tmp_path / "dest",
        "http://ollama",
        transport=httpx.MockTransport(backend),
        load_confirm=load,
        reserve_memory_bytes=0,
        reserved_bytes=0,
    )
    await source.open()
    await dest.open()
    try:
        offers = await source.inventory("new-trusted-peer")
        assert len(offers) == 1
        offer = offers[0]
        assert offer.manifest_digest == offer.calculated_digest()
        assert offer.license == show["license"]
        assert str(tmp_path) not in offer.model_dump_json()
        assert offer.ollama.parameters["stop"] == ["end-one", "end-two"]

        async def manifest(_source, digest):
            return await source.source_manifest("new-trusted-peer", digest)

        async def chunk(_source, spec):
            return await source.source_chunk("new-trusted-peer", spec)

        request = TransferRequest(
            digest=offer.digest,
            manifest_digest=offer.manifest_digest,
            source="source",
            permit=True,
            license_approved=True,
        )
        await dest.start_transfer(request, manifest, chunk)
        await dest._tasks[offer.digest]
        assert (await dest.status())[0].state == "ready"
        assert created[0]["license"] == show["license"]
        assert created[0]["template"] == show["template"]
        assert created[0]["system"] == show["system"]
        assert created[0]["parameters"] == {
            "temperature": 0.25,
            "num_ctx": 4096,
            "stop": ["end-one", "end-two"],
        }
        assert await dest.source_manifest("another-trusted-peer", offer.digest) == offer
    finally:
        await source.close()
        await dest.close()


@pytest.mark.asyncio
async def test_automatic_permission_overrides_persist_and_removed_models_withdraw(tmp_path):
    data, _, _, tags, transport = model_fixture(tmp_path)
    store = tmp_path / "store"
    manager = ModelSharing(store, "http://ollama", transport=transport, discover_installed=True)
    await manager.open()
    offer = (await manager.inventory("one"))[0]
    await manager.set_permission(offer.digest, ["one"], True, True)
    assert not await manager.inventory("two")
    chunk = await manager.source_chunk("one", ChunkRequest(digest=offer.digest, offset=0, length=4))
    assert base64.b64decode(chunk.data) == data[:4]
    await manager.close()

    manager = ModelSharing(store, "http://ollama", transport=transport, discover_installed=True)
    await manager.open()
    try:
        assert not await manager.inventory("two")
        await manager.set_permission(offer.digest, [], False, False)
        with pytest.raises(AdmissionError, match="artifact_not_found"):
            await manager.source_chunk("one", ChunkRequest(digest=offer.digest, offset=0, length=4))
        await manager.set_permission(offer.digest, ["*"], True, True)
        assert await manager.inventory("new-peer")
        manager.catalog._expires = 0
        tags["models"] = []
        assert not await manager.inventory("one")
    finally:
        await manager.close()


@pytest.mark.asyncio
@pytest.mark.parametrize(
    "unsupported", ["safetensors", "vision", "adapter", "symlink", "relative", "magic"]
)
async def test_discovery_does_not_export_partial_or_unsafe_models(tmp_path, unsupported):
    _, path, show, _, transport = model_fixture(tmp_path)
    if unsupported == "safetensors":
        show["details"]["format"] = "safetensors"
    elif unsupported == "vision":
        show["capabilities"].append("vision")
    elif unsupported == "adapter":
        show["modelfile"] += "ADAPTER /other/file\n"
    elif unsupported == "symlink":
        original = path.with_suffix(".real")
        path.rename(original)
        path.symlink_to(original)
    elif unsupported == "relative":
        show["modelfile"] = f"FROM {path.name}"
    else:
        path.write_bytes(b"bad file")
    manager = ModelSharing(
        tmp_path / "store", "http://ollama", transport=transport, discover_installed=True
    )
    await manager.open()
    try:
        assert await manager.inventory("peer") == []
    finally:
        await manager.close()


@pytest.mark.asyncio
async def test_opt_out_does_not_probe_backend_and_registered_defaults_share(tmp_path):
    _, path, _, _, _ = model_fixture(tmp_path)

    def no_backend(request):
        pytest.fail(f"unexpected automatic discovery {request.url.path}")

    manager = ModelSharing(
        tmp_path / "store",
        "http://ollama",
        transport=httpx.MockTransport(no_backend),
        discover_installed=False,
    )
    await manager.open()
    try:
        assert await manager.inventory("peer") == []
        data = path.read_bytes()
        offer = ArtifactManifest(
            model_id="manual",
            digest=hashlib.sha256(data).hexdigest(),
            size_bytes=len(data),
            quantization="Q4",
            provenance="test",
            license="MIT",
            required_memory_bytes=1,
            manifest_digest="0" * 64,
        )
        # New optional metadata must not change pre-existing canonical digests.
        original = offer.model_dump(exclude={"manifest_digest"})
        assert "ollama" not in original
        offer.manifest_digest = offer.calculated_digest()
        await manager.register(LocalArtifact(manifest=offer, path=str(path)))
        assert await manager.source_manifest("any-authenticated-peer", offer.digest) == offer
        await manager.set_permission(offer.digest, [], False, False)
        assert not await manager.inventory("any-authenticated-peer")
        assert PeerSettings().model_auto_share
    finally:
        await manager.close()


@pytest.mark.asyncio
async def test_local_status_inventory_does_not_wait_for_slow_discovery(tmp_path):
    started = asyncio.Event()
    stopped = asyncio.Event()

    async def slow_backend(request):
        started.set()
        try:
            await asyncio.Event().wait()
        finally:
            stopped.set()

    manager = ModelSharing(
        tmp_path,
        "http://ollama",
        transport=httpx.MockTransport(slow_backend),
        discover_installed=True,
    )
    await manager.open()
    try:
        assert await asyncio.wait_for(manager.inventory(), timeout=1) == []
        await asyncio.wait_for(started.wait(), timeout=1)
    finally:
        await manager.close()
    assert stopped.is_set()


@pytest.mark.asyncio
async def test_full_metadata_inventory_stays_inside_signed_response_budget(tmp_path):
    _, path, show, _, transport = model_fixture(tmp_path)
    manager = ModelSharing(
        tmp_path / "store", "http://ollama", transport=transport, discover_installed=True
    )
    await manager.open()
    try:
        base = (await manager.inventory("peer"))[0]
        for index in range(20):
            data = b"GGUF" + str(index).encode()
            path = tmp_path / f"manual-{index}.gguf"
            path.write_bytes(data)
            offer = base.model_copy(deep=True)
            offer.digest = hashlib.sha256(data).hexdigest()
            offer.size_bytes = len(data)
            offer.model_id = f"model-{index}"
            offer.license = "L" * 65536
            offer.ollama.template = "T" * 65536
            offer.ollama.system = "S" * 65536
            offer.manifest_digest = offer.calculated_digest()
            await manager.register(LocalArtifact(manifest=offer, path=str(path)))
        inventory = await manager.inventory("peer")
        assert 0 < len(inventory) < 20
        assert len(ModelInventory(models=inventory).model_dump_json().encode()) < 2 * CHUNK_SIZE
        # The bound limits this advisory listing, not authorization to fetch a model.
        assert await manager.source_manifest("peer", offer.digest) == offer
    finally:
        await manager.close()
